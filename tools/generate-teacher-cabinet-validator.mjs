import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import compiler from '../packages/contract-validation/ajv-config.cjs';
import builder from '../packages/contract-validation/view-builder.cjs';

const require = createRequire(import.meta.url);
const standalone = require('ajv/dist/standalone').default;
const { uuid } = require('ajv-formats/dist/formats.js').fullFormats;
const source = readFileSync(new URL('../contracts/telegram-return.openapi.json', import.meta.url));
const pinned = '430a2be52599c46f49ef1263ff579cd5c993954f62b7a37fd1a10814c8d05455';
assert.equal(createHash('sha256').update(source).digest('hex'), pinned, 'Cabinet contract release changed');
const { view } = builder.buildView(source);
const ajv = compiler.createAjv();
Object.assign(ajv.opts.code, { source: true, esm: true, lines: true });
// The release compiler wraps every format to reject raw line separators. A single
// regexp gives standalone Ajv the same UUID predicate without a captured closure.
assert(uuid instanceof RegExp);
ajv.addFormat('uuid', new RegExp('^(?![\\s\\S]*[\\r\\n\\u2028\\u2029])(?:' + uuid.source + ')', uuid.flags));
ajv.addSchema(view);
const roots = Object.fromEntries(['QuestionWrite', 'Version'].map(name => [name, view.$id + '#/$defs/' + name]));
const code = standalone(ajv, roots);
// Keep Ajv's own code-point counter, with a static ESM import for Workers bundling.
const counter = 'require("ajv/dist/runtime/ucs2length").default';
assert.deepEqual(code.match(/require\([^)]+\)\.default/g), [counter], 'Review new validator runtime dependencies');
const esm = code.replace(counter, 'unicodeLength.default');
assert.doesNotMatch(esm, /\brequire\(|\beval\(|new Function\(/);

const output = '// Generated by tools/generate-teacher-cabinet-validator.mjs from contract SHA-256 ' + pinned + '.\n' +
  'import unicodeLength from "ajv/dist/runtime/ucs2length.js";\n' + esm +
  '\nexport function validate(name, value) {\n' +
  '  if (name === "QuestionWrite") return QuestionWrite(value);\n' +
  '  if (name === "Version") return Version(value);\n' +
  '  return false;\n}\n';
const destination = new URL('../packages/contract-validation/teacher-cabinet.mjs', import.meta.url);
if (process.argv[2] === '--check' && process.argv.length === 3) {
  assert.equal(readFileSync(destination, 'utf8') === output, true, 'Regenerate the Worker cabinet validator');
} else if (process.argv.length === 2) {
  writeFileSync(destination, output);
} else {
  throw Error('Use --check to verify, or no arguments to generate');
}
